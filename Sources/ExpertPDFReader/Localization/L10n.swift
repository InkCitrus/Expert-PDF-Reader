    public static func tr(_ zh: String, _ en: String) -> String {
        let lang = resolvedLanguage
        switch lang {
        case .zhHans:
            return zh
        case .en, .system:
            return en
        default:
            let compositeKey = "\(zh)|||\(en)"
            if let table = catalog[lang.rawValue], let found = table[compositeKey] {
                return found
            }
            return en
        }
    }

    public static func pageCountText(_ count: Int) -> String {
        switch resolvedLanguage {
        case .zhHans, .zhHant: return "\(count) 页".replacingOccurrences(of: "页", with: resolvedLanguage == .zhHant ? "頁" : "页")
