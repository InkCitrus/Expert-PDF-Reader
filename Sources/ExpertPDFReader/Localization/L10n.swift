/// Supported application UI languages (12 languages + Follow System).
public enum AppLanguage: String, CaseIterable, Identifiable, Codable {
    case system = "system"
    case zhHans = "zh-Hans"
    case zhHant = "zh-Hant"
    case en = "en"
    case ja = "ja"
    case ko = "ko"
    case fr = "fr"
    case de = "de"
    case es = "es"
    case it = "it"
    case pt = "pt"
    case ru = "ru"
    case uk = "uk"

    public var id: String { rawValue }

    /// The user's system-wide language order. `Locale.preferredLanguages` would also reflect the app's own
    /// `AppleLanguages`, which is set to an explicitly chosen language for the menu bar.
    private static var systemPreferredLanguages: [String] {
        let global = CFPreferencesCopyValue(
            "AppleLanguages" as CFString,
            kCFPreferencesAnyApplication,
            kCFPreferencesCurrentUser,
            kCFPreferencesAnyHost
        ) as? [String]
        return global ?? Locale.preferredLanguages
    }

    /// Resolves `.system` against the system's preferred languages into a concrete language.
    public var resolved: AppLanguage {
        guard self == .system else { return self }
        for pref in Self.systemPreferredLanguages {
            let lower = pref.lowercased()
            if lower.hasPrefix("zh-hant") || lower.hasPrefix("zh-tw") || lower.hasPrefix("zh-hk") || lower.hasPrefix("zh-mo") {
                return .zhHant
            }
            if lower.hasPrefix("zh") { return .zhHans }
            if lower.hasPrefix("ja") { return .ja }
            if lower.hasPrefix("ko") { return .ko }
            if lower.hasPrefix("fr") { return .fr }
            if lower.hasPrefix("de") { return .de }
            if lower.hasPrefix("es") { return .es }
            if lower.hasPrefix("it") { return .it }
            if lower.hasPrefix("pt") { return .pt }
            if lower.hasPrefix("ru") { return .ru }
            if lower.hasPrefix("uk") { return .uk }
            if lower.hasPrefix("en") { return .en }
        }
        return .en
    }

    public var resolvedIsChinese: Bool {
        let r = resolved
        return r == .zhHans || r == .zhHant
    }

    public var locale: Locale {
        Locale(identifier: resolved.rawValue)
    }

    public var title: String {
        switch self {
        case .system: return L10n.tr("跟随系统", "Follow System")
        case .zhHans: return "简体中文"
        case .zhHant: return "繁體中文"
        case .en:     return "English"
        case .ja:     return "日本語"
        case .ko:     return "한국어"
        case .fr:     return "Français"
        case .de:     return "Deutsch"
        case .es:     return "Español"
        case .it:     return "Italiano"
        case .pt:     return "Português"
        case .ru:     return "Русский"
        case .uk:     return "Українська"
        }
    }

    public var shortTitle: String {
        switch self {
        case .system: return L10n.tr("自动", "Auto")
        case .zhHans: return "简"
        case .zhHant: return "繁"
        case .en:     return "EN"
        case .ja:     return "JA"
        case .ko:     return "KO"
        case .fr:     return "FR"
        case .de:     return "DE"
        case .es:     return "ES"
        case .it:     return "IT"
        case .pt:     return "PT"
        case .ru:     return "RU"
        case .uk:     return "UK"
        }
    }
}

